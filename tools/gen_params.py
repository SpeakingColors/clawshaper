#!/usr/bin/env python3
"""Generates src/plugin/ParamTable.h and ParamMap.h from tools/params.json (dumped from the approved mockup)."""
import json
d=json.load(open('tools/params.json'))
UI=('.view','.zoom')
rows=[p for p in d if not (p['id'].endswith(UI) or p['id']=='m.fft')]
uirows=[p for p in d if p['id'].endswith(UI) or p['id']=='m.fft']
def F(v):
    t='%g'%v
    return (t if ('.' in t or 'e' in t) else t+'.0')+'f'
def nice(i):
    a,b=i.split('.',1)
    return ('Main ' if a=='m' else 'Band %d '%(int(a[1])+1))+b
out=['// Generated by tools/gen_params.py from the mockup parameter table. Do not edit by hand.','#pragma once','namespace cs {','struct PDef { const char* id; const char* name; float mn, mx, df; bool log, isInt; };','inline constexpr PDef kParams[] = {']
for p in rows:
    out.append('    {"%s","%s",%s,%s,%s,%s,%s},'%(p['id'],nice(p['id']),F(p['min']),F(p['max']),F(p['def']),'true' if p.get('log') else 'false','true' if p.get('int') else 'false'))
out+=['};','inline constexpr int kNumParams = (int)(sizeof(kParams)/sizeof(kParams[0]));','// window-only settings (not automatable): stored in the saved state as properties "ui.<id>"','inline constexpr PDef kUi[] = {']
for p in uirows:
    out.append('    {"%s","%s",%s,%s,%s,%s,%s},'%(p['id'],p['id'],F(p['min']),F(p['max']),F(p['def']),'true' if p.get('log') else 'false','true' if p.get('int') else 'false'))
out+=['};','inline constexpr int kNumUi = (int)(sizeof(kUi)/sizeof(kUi[0]));','}']
open('src/plugin/ParamTable.h','w').write('\n'.join(out)+'\n')
ix={p['id']:n for n,p in enumerate(rows)}
L=['// Generated by tools/gen_params.py. Do not edit by hand.','#pragma once','#include "../core/ClawShaperCore.h"','#include "ParamTable.h"','namespace cs {','inline void applyParams(const float* v, ShaperP& m) {']
def put(lhs,i,kind):
    e='v[%d]'%ix[i]
    if kind=='b': e+=' > 0.5f'
    elif kind=='i': e='(int) (%s + 0.5f)'%e
    L.append('    %s = %s;'%(lhs,e))
for lhs,i,k in [('m.byp','m.byp','b'),('m.bands','m.bands','i'),('m.slope','m.slope','i'),('m.mix','m.mix','f'),('m.inG','m.inG','f'),('m.outG','m.outG','f'),('m.limOn','m.limOn','b'),('m.ceil','m.ceil','f'),('m.limAuto','m.lAuto','b'),('m.limRel','m.lRel','f'),('m.la','m.la','f'),('m.listen','m.listen','i'),('m.boost','m.boost','i')]: put(lhs,i,k)
for n in (1,2,3): put('m.x[%d]'%(n-1),'m.x%d'%n,'f')
for b in range(4):
    for k,f,t in [('on','on','b'),('mute','mute','b'),('solo','solo','b'),('atk','atk','f'),('sus','sus','f'),('spd','spd','i'),('thr','thr','f'),('max','max','f'),('outG','outG','f'),('mix','mix','f')]:
        put('m.b[%d].%s'%(b,f),'b%d.%s'%(b,k),t)
L+=['}','}']
open('src/plugin/ParamMap.h','w').write('\n'.join(L)+'\n'); print(len(rows),'host params',len(uirows),'ui')
