#!/usr/bin/env python3
"""Generate src/editor/Presets.h from tools/presets.json (dumped from the approved mockup)."""
import json
d = json.load(open('tools/presets.json'))['FACT']
def F(v):
    t = '%.9g' % v
    return t + ('f' if ('.' in t or 'e' in t) else '.0f')
o = ['// Generated by tools/gen_presets.py from the mockup. Do not edit by hand.', '#pragma once', 'namespace presets {',
     'struct KV { const char* id; float v; };',
     'struct Pre { const char* name; const char* type; const KV* kv; int n; };']
pre = []
for i, p in enumerate(d):
    nm = 'p%d' % i
    o.append('inline constexpr KV %s[] = { %s };' % (nm, ', '.join('{ "%s", %s }' % (k, F(float(v))) for k, v in p['p'].items()) or '{ "m.bands", 4.0f }'))
    pre.append('  { "%s", "%s", %s, %d },' % (p['name'].replace('"', "'"), p['type'], nm, max(1, len(p['p']))))
o.append('inline constexpr Pre kPre[] = {'); o += pre; o.append('};')
o.append('inline constexpr int kNumPre = %d;' % len(pre))
o.append('} // namespace presets')
open('src/editor/Presets.h', 'w').write('\n'.join(o) + '\n')
print('presets', len(pre))
